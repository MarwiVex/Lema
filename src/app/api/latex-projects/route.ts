import { NextResponse } from 'next/server';
import { prisma } from '@/lib/prisma';
import { compileLatexWithTectonic } from '@/lib/tectonic';
import { handleApiError } from '@/lib/apiError';

export const dynamic = 'force-dynamic';

// ─── GET: obtener proyecto(s) ──────────────────────────────────────────────────
export async function GET(req: Request) {
  try {
    const { searchParams } = new URL(req.url);
    const id = searchParams.get('id');
    const folderId = searchParams.get('folderId');

    if (id) {
      const project = await prisma.latexProject.findUnique({
        where: { id },
        select: {
          id: true,
          title: true,
          description: true,
          compiledAt: true,
          folderId: true,
          createdAt: true,
          updatedAt: true,
          files: { orderBy: [{ isMain: 'desc' }, { filename: 'asc' }] },
        },
      });
      if (!project) return NextResponse.json({ error: 'Not found' }, { status: 404 });
      return NextResponse.json({ ...project, hasPdf: Boolean(project.compiledAt) });
    }

    const projects = await prisma.latexProject.findMany({
      where: folderId ? { folderId } : {},
      select: {
        id: true,
        title: true,
        description: true,
        compiledAt: true,
        folderId: true,
        createdAt: true,
        updatedAt: true,
      },
      orderBy: { updatedAt: 'desc' },
    });
    return NextResponse.json(projects);
  } catch (error) {
    return handleApiError(error, 'Error fetching LaTeX projects');
  }
}

// ─── POST: crear proyecto ──────────────────────────────────────────────────────
export async function POST(req: Request) {
  try {
    const { title, folderId, description, files } = await req.json();

    if (!title) return NextResponse.json({ error: 'title es requerido' }, { status: 400 });
    if (!files || !Array.isArray(files) || files.length === 0) {
      return NextResponse.json({ error: 'files es requerido y debe tener al menos un archivo' }, { status: 400 });
    }

    const uniqueFilesMap = new Map<
      string,
      { filename: string; content: string; isBinary: boolean; isMain: boolean }
    >();
    let hasMainAlready = false;
    for (const f of files) {
      if (!f?.filename || f.content === undefined) continue;
      const existing = uniqueFilesMap.get(f.filename);
      let isMainFlag = Boolean(f.isMain) || Boolean(existing?.isMain);
      if (isMainFlag && hasMainAlready && !existing?.isMain) {
        isMainFlag = false;
      }
      if (isMainFlag) hasMainAlready = true;
      uniqueFilesMap.set(f.filename, {
        filename: f.filename,
        content: f.content,
        isBinary: Boolean(f.isBinary),
        isMain: isMainFlag,
      });
    }
    const uniqueFiles = Array.from(uniqueFilesMap.values());
    if (uniqueFiles.length === 0) {
      return NextResponse.json({ error: 'No hay archivos válidos en el proyecto' }, { status: 400 });
    }

    const project = await prisma.latexProject.create({
      data: {
        title,
        description: description || null,
        folderId: folderId || null,
        files: {
          create: uniqueFiles,
        },
      },
      select: {
        id: true,
        title: true,
        description: true,
        compiledAt: true,
        folderId: true,
        createdAt: true,
        updatedAt: true,
      },
    });

    return NextResponse.json(project, { status: 201 });
  } catch (error) {
    return handleApiError(error, 'Error creating LaTeX project');
  }
}

// ─── PUT: actualizar archivo(s) o compilar ────────────────────────────────────
export async function PUT(req: Request) {
  try {
    const body = await req.json();
    const { id, action } = body;

    if (!id) return NextResponse.json({ error: 'id es requerido' }, { status: 400 });

    if (action === 'compile') {
      return await compileProject(id);
    }

    // ── set_pdf: persist PDF generated by WASM in the browser ─────────────
    if (action === 'set_pdf') {
      const { pdfBase64 } = body;
      if (!pdfBase64) return NextResponse.json({ error: 'pdfBase64 es requerido' }, { status: 400 });
      const updated = await prisma.latexProject.update({
        where: { id },
        data: { pdfBase64, compiledAt: new Date() },
        select: { id: true, compiledAt: true },
      });
      return NextResponse.json(updated);
    }

    if (action === 'update_file') {
      const { fileId, content } = body;
      if (!fileId || content === undefined) {
        return NextResponse.json({ error: 'fileId y content son requeridos' }, { status: 400 });
      }
      const updatedProject = await prisma.$transaction(async (tx) => {
        const updated = await tx.latexFile.updateMany({
          where: { id: fileId, projectId: id },
          data: { content },
        });
        if (updated.count === 0) {
          throw { code: 'P2025' };
        }
        return tx.latexProject.update({
          where: { id },
          data: { updatedAt: new Date() },
          select: { id: true, updatedAt: true },
        });
      });
      return NextResponse.json({ id: fileId, updatedAt: updatedProject.updatedAt });
    }

    if (action === 'update_files') {
      const { files } = body;
      if (!Array.isArray(files)) {
        return NextResponse.json({ error: 'files debe ser un arreglo' }, { status: 400 });
      }
      if (files.length === 0) {
        return NextResponse.json({ updatedCount: 0 });
      }
      for (const f of files) {
        if (!f?.fileId || f.content === undefined) {
          return NextResponse.json({ error: 'Cada entrada requiere fileId y content' }, { status: 400 });
        }
      }

      const now = new Date();
      await prisma.$transaction(async (tx) => {
        for (const f of files as { fileId: string; content: string }[]) {
          const updated = await tx.latexFile.updateMany({
            where: { id: f.fileId, projectId: id },
            data: { content: f.content },
          });
          if (updated.count === 0) {
            throw { code: 'P2025' };
          }
        }
        await tx.latexProject.update({
          where: { id },
          data: { updatedAt: now },
          select: { id: true },
        });
      });
      return NextResponse.json({ updatedCount: files.length, updatedAt: now.toISOString() });
    }

    if (action === 'add_file') {
      const { filename, content, isBinary, isMain } = body;
      if (!filename || content === undefined) {
        return NextResponse.json({ error: 'filename y content son requeridos' }, { status: 400 });
      }
      const file = await prisma.$transaction(async (tx) => {
        if (isMain) {
          await tx.latexFile.updateMany({
            where: { projectId: id },
            data: { isMain: false },
          });
        }
        const created = await tx.latexFile.create({
          data: { projectId: id, filename, content, isBinary: isBinary ?? false, isMain: isMain ?? false },
        });
        await tx.latexProject.update({
          where: { id },
          data: { updatedAt: new Date() },
          select: { id: true },
        });
        return created;
      });
      return NextResponse.json(file, { status: 201 });
    }

    if (action === 'delete_file') {
      const { fileId } = body;
      if (!fileId) return NextResponse.json({ error: 'fileId es requerido' }, { status: 400 });
      await prisma.$transaction(async (tx) => {
        const deleted = await tx.latexFile.deleteMany({
          where: { id: fileId, projectId: id },
        });
        if (deleted.count === 0) {
          throw { code: 'P2025' };
        }
        await tx.latexProject.update({
          where: { id },
          data: { updatedAt: new Date() },
          select: { id: true },
        });
      });
      return NextResponse.json({ success: true });
    }

    if (action === 'set_main') {
      const { fileId } = body;
      if (!fileId) return NextResponse.json({ error: 'fileId es requerido' }, { status: 400 });
      await prisma.$transaction(async (tx) => {
        const target = await tx.latexFile.findFirst({
          where: { id: fileId, projectId: id },
          select: { id: true },
        });
        if (!target) {
          throw { code: 'P2025' };
        }
        await tx.latexFile.updateMany({
          where: { projectId: id },
          data: { isMain: false },
        });
        await tx.latexFile.update({
          where: { id: fileId },
          data: { isMain: true },
        });
        await tx.latexProject.update({
          where: { id },
          data: { updatedAt: new Date() },
          select: { id: true },
        });
      });
      return NextResponse.json({ success: true });
    }

    if (action === 'update_title') {
      const { title, description } = body;
      if (!title) return NextResponse.json({ error: 'title es requerido' }, { status: 400 });
      const project = await prisma.latexProject.update({
        where: { id },
        data: { title, description },
        select: {
          id: true,
          title: true,
          description: true,
          compiledAt: true,
          folderId: true,
          updatedAt: true,
        },
      });
      return NextResponse.json(project);
    }

    if (action === 'move_folder') {
      const { folderId } = body;
      const project = await prisma.latexProject.update({
        where: { id },
        data: { folderId: folderId || null },
        select: {
          id: true,
          title: true,
          description: true,
          compiledAt: true,
          folderId: true,
          updatedAt: true,
        },
      });
      return NextResponse.json(project);
    }

    return NextResponse.json({ error: 'Acción desconocida' }, { status: 400 });
  } catch (error) {
    return handleApiError(error, 'Error updating LaTeX project');
  }
}

// ─── DELETE: eliminar proyecto ─────────────────────────────────────────────────
export async function DELETE(req: Request) {
  try {
    const { searchParams } = new URL(req.url);
    const id = searchParams.get('id');
    if (!id) return NextResponse.json({ error: 'id es requerido' }, { status: 400 });

    await prisma.latexProject.delete({ where: { id } });
    return NextResponse.json({ success: true });
  } catch (error) {
    return handleApiError(error, 'Error deleting LaTeX project');
  }
}

// ─── Helper: compilar un proyecto con Tectonic (servidor local únicamente) ────
async function compileProject(projectId: string): Promise<NextResponse> {
  try {
    const project = await prisma.latexProject.findUnique({
      where: { id: projectId },
      include: { files: true },
    });

    if (!project) return NextResponse.json({ error: 'Proyecto no encontrado' }, { status: 404 });

    const mainFile = project.files.find((f) => f.isMain) ?? project.files.find((f) => f.filename.endsWith('.tex'));
    if (!mainFile) return NextResponse.json({ error: 'No se encontró el archivo .tex principal' }, { status: 400 });

    const result = await compileLatexWithTectonic({
      files: project.files.map((f) => ({
        filename: f.filename,
        content: f.content,
        isBinary: f.isBinary,
      })),
      mainFilename: mainFile.filename,
      allowDocker: false,
    });

    if (!result.ok) {
      return NextResponse.json(
        {
          error: result.error,
          details:
            result.details +
            '\n\n💡 Usa el botón "Compilar en Navegador (WASM)" — funciona 100% sin servidor.',
        },
        { status: 500 }
      );
    }

    const pdfBase64 = result.pdfBuffer.toString('base64');

    const updated = await prisma.latexProject.update({
      where: { id: projectId },
      data: { pdfBase64, compiledAt: new Date() },
      select: { id: true, compiledAt: true },
    });

    return NextResponse.json({
      id: updated.id,
      compiledAt: updated.compiledAt,
      hasPdf: true,
    });
  } catch (error: any) {
    console.error('[compile] Error:', error);
    return NextResponse.json({ error: error.message }, { status: 500 });
  }
}
